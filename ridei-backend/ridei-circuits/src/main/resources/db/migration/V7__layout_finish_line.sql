-- Línea de meta de cada trazado (layout.finish_line) y meta de Montmeló.
--
-- finish_line: LineString de 2 puntos (SRID 4326, x = longitud, y = latitud), la puerta que
-- cruza la pista: el primero es el extremo de la IZQUIERDA y el segundo el de la DERECHA,
-- mirando en el sentido de la marcha. NULL = meta desconocida. La lee y escribe
-- LayoutGeometryWkt (que sustituye a LayoutPathWkt, citado en V6).
--
-- Si un trazado tiene meta, su dibujo (path) EMPIEZA en el punto donde la meta lo corta
-- (LayoutPath.startingAt); por eso se reescriben aquí los dibujos que la reciben.
--
-- ─────────────────────────────────────────────────────────────────────────────────────────
-- Geometría: © OpenStreetMap contributors, disponible bajo la Open Database License (ODbL)
-- https://www.openstreetmap.org/copyright — datos descargados el 2026-11-20 (API 0.6 /map).
--
-- Meta de Montmeló: nodo 14202158171 (raceway=finish), el "finish" de las relaciones
-- type=circuit 284540 (GP sin chicane), 2049529 (GP con chicane) y 21420925 (MotoGP), cuyas
-- vías coinciden con las usadas en V6 para los dibujos. La comparten GP, GP con chicane y
-- Nacional; la Escuela no pasa por la recta (meta NULL). Puerta perpendicular a la marcha que
-- pasa por el nodo: 10 m hacia la izquierda y 7 m hacia la derecha, donde está el pit lane (su
-- eje, vía 178416729, a 14 m del de la pista): llega hasta el punto medio, el muro de boxes,
-- sin entrar en el pit lane. La salida (raceway=start, nodo 385973430) está 127 m antes y no
-- se guarda.
--
-- Los dibujos se recalculan con el anillo empezando en el nodo de meta (Douglas-Peucker, 2,5 m,
-- conserva siempre el primer punto):
--   GP 75 puntos, 4653 m · GP con chicane 77 puntos, 4668 m · Nacional 44 puntos, 2972 m
--
-- Calafat: sin meta en OSM ni en las fuentes consultadas; queda NULL hasta tener coordenadas.
-- ─────────────────────────────────────────────────────────────────────────────────────────

ALTER TABLE layout ADD COLUMN finish_line geometry(LineString, 4326);

ALTER TABLE layout ADD CONSTRAINT ck_layout_finish_line
    CHECK (finish_line IS NULL OR (ST_NPoints(finish_line) = 2
                                   AND ST_XMin(finish_line) >= -180 AND ST_XMax(finish_line) <= 180
                                   AND ST_YMin(finish_line) >= -90 AND ST_YMax(finish_line) <= 90));

